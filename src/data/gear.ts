/* ---------- Unified "family" model ----------
   A family is a brand+series that expands into a checkbox picker instead of
   flooding the search list with every variant. Each family has:
   - cat: which checklist category it belongs to
   - label: "Brand Series" — what you type to find it
   - info: short subtitle shown under the picker header (mount, physical size…)
   - wholeSetSpec: if set, shows a checkable "Whole Set" row that adds ONE
     bundled line item; null means there's no meaningful bundle (e.g. matteboxes/
     Teradek/monitors — you pick a specific configuration, not "everything")
   - variants: the individual pickable items (combined as "label + variant") */
